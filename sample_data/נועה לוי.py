# הסבר: מספרים קטנים מ-2 אינם ראשוניים. אחרת בודקים אם יש מחלק בין 2 לשורש של n.
# אם נמצא מחלק - המספר לא ראשוני. אם לא נמצא - הוא ראשוני.

def is_prime(n):
    if n < 2:
        return False
    i = 2
    while i * i <= n:
        if n % i == 0:
            return False
        i += 1
    return True
